#!/usr/bin/env python3
"""Build the static pages by inlining shared partials and site variables.

Usage:
    python3 build.py

Edit the pages in src/ and shared fragments in partials/, change contact
details in site_config.py, then run this script. The generated HTML is written to the
project root so it can be opened directly or uploaded to any static host.
"""

from pathlib import Path
import re
import textwrap

import site_config

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"

INCLUDE_RE = re.compile(
    r"^([ \t]*)<!--\s*include:\s*([^\s]+)\s*-->[ \t]*\n?",
    re.MULTILINE,
)

PLACEHOLDER_RE = re.compile(r"\{\{\s*([a-z0-9_]+)\s*\}\}")


def inline_includes(html: str) -> str:
    def replace(match: re.Match[str]) -> str:
        indent, partial_path = match.groups()
        partial = (ROOT / partial_path).read_text(encoding="utf-8")
        partial = textwrap.dedent(partial).rstrip("\n")
        return textwrap.indent(partial, indent) + "\n"

    return INCLUDE_RE.sub(replace, html)


def add_generated_notice(html: str, source: Path) -> str:
    notice = (
        f"<!-- Generated by build.py from {source.relative_to(ROOT)}. "
        f"Edit {source.relative_to(ROOT)}, not this file. -->"
    )
    return html.replace("<!DOCTYPE html>", f"<!DOCTYPE html>\n{notice}", 1)


def fill_placeholders(html: str, source: Path) -> str:
    def replace(match: re.Match[str]) -> str:
        key = match.group(1)
        try:
            return site_config.VARIABLES[key]
        except KeyError:
            raise ValueError(f"{source}: onbekende placeholder {{{{ {key} }}}}") from None

    return PLACEHOLDER_RE.sub(replace, html)


def main() -> None:
    for source in sorted(SRC.glob("*.html")):
        html = inline_includes(source.read_text(encoding="utf-8"))
        html = fill_placeholders(html, source)
        html = add_generated_notice(html, source)
        output = ROOT / source.name
        output.write_text(html, encoding="utf-8")
        print(f"built {output.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
